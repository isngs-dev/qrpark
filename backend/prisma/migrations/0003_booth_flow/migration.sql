    CHECK ("validation_status" <> 'VALIDATED' OR "payment_status" = 'PAID'),
  ADD CONSTRAINT "ticket_validated_fields_check" CHECK (
    ("validation_status" = 'VALIDATED') = ("validated_at" IS NOT NULL)
    AND ("validated_at" IS NULL) = ("validated_gate_id" IS NULL)
    AND ("validated_at" IS NULL) = ("validated_by_id" IS NULL)
  ),
  -- Valid while now() < valid_until: never validated at or after it.
  ADD CONSTRAINT "ticket_validated_before_expiry_check"
    CHECK ("validated_at" IS NULL OR "validated_at" < "valid_until");

-- A new ticket starts UNPAID and NOT_VALIDATED; valid_until is ALWAYS the
-- end of its issue day, whatever the insert says. issued_at defaults to
-- now(); only raw SQL (tests, the Sprint 6 run) sets an earlier one.
CREATE FUNCTION "ticket_insert_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."payment_status" <> 'UNPAID' OR NEW."validation_status" <> 'NOT_VALIDATED' THEN
    RAISE EXCEPTION 'ticket insert refused: a new ticket is UNPAID and NOT_VALIDATED'
      USING ERRCODE = 'check_violation';
  END IF;
  NEW."issued_at" := COALESCE(NEW."issued_at", now());
  NEW."valid_until" := lagos_day_end(NEW."issued_at");
  RETURN NEW;
END;
$$;

CREATE TRIGGER "ticket_insert_guard"
  BEFORE INSERT ON "ticket"
  FOR EACH ROW EXECUTE FUNCTION "ticket_insert_guard"();

-- After insert: the identity of a ticket never changes, PAID and VALIDATED
-- never go back (THE FREEZE: lifted only by a future migration if Phase 2
-- adds refunds), and PAID needs a SUCCESS payment. The payment belonging to
-- this ticket is the composite key's job (ticket_paid_payment_id_id_fkey).
CREATE FUNCTION "ticket_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  paying_status text;
BEGIN
  IF NEW."token" IS DISTINCT FROM OLD."token" THEN RAISE EXCEPTION 'ticket token cannot change'; END IF;
  IF NEW."ticket_number" IS DISTINCT FROM OLD."ticket_number" THEN RAISE EXCEPTION 'ticket ticket_number cannot change'; END IF;
  IF NEW."fee_kobo" IS DISTINCT FROM OLD."fee_kobo" THEN RAISE EXCEPTION 'ticket fee_kobo cannot change'; END IF;
  IF NEW."category_id" IS DISTINCT FROM OLD."category_id" THEN RAISE EXCEPTION 'ticket category_id cannot change'; END IF;
  IF NEW."category_code" IS DISTINCT FROM OLD."category_code" THEN RAISE EXCEPTION 'ticket category_code cannot change'; END IF;
  IF NEW."category_name" IS DISTINCT FROM OLD."category_name" THEN RAISE EXCEPTION 'ticket category_name cannot change'; END IF;
  IF NEW."issued_at" IS DISTINCT FROM OLD."issued_at" THEN RAISE EXCEPTION 'ticket issued_at cannot change'; END IF;
  IF NEW."valid_until" IS DISTINCT FROM OLD."valid_until" THEN RAISE EXCEPTION 'ticket valid_until cannot change'; END IF;
  IF NEW."idempotency_key" IS DISTINCT FROM OLD."idempotency_key" THEN RAISE EXCEPTION 'ticket idempotency_key cannot change'; END IF;
  IF NEW."site_id" IS DISTINCT FROM OLD."site_id" THEN RAISE EXCEPTION 'ticket site_id cannot change'; END IF;
  IF NEW."operator_id" IS DISTINCT FROM OLD."operator_id" THEN RAISE EXCEPTION 'ticket operator_id cannot change'; END IF;
  IF NEW."gate_id" IS DISTINCT FROM OLD."gate_id" THEN RAISE EXCEPTION 'ticket gate_id cannot change'; END IF;
  IF NEW."device_ref" IS DISTINCT FROM OLD."device_ref" THEN RAISE EXCEPTION 'ticket device_ref cannot change'; END IF;

  IF OLD."payment_status" = 'PAID' AND NEW."payment_status" <> 'PAID' THEN
    RAISE EXCEPTION 'ticket payment_status cannot go back from PAID';
  END IF;
  IF OLD."paid_payment_id" IS NOT NULL AND NEW."paid_payment_id" IS DISTINCT FROM OLD."paid_payment_id" THEN
    RAISE EXCEPTION 'ticket paid_payment_id cannot change once set';
  END IF;
  IF OLD."paid_at" IS NOT NULL AND NEW."paid_at" IS DISTINCT FROM OLD."paid_at" THEN
    RAISE EXCEPTION 'ticket paid_at cannot change once set';
  END IF;
  IF OLD."validation_status" = 'VALIDATED' AND NEW."validation_status" <> 'VALIDATED' THEN
    RAISE EXCEPTION 'ticket validation_status cannot go back from VALIDATED';
  END IF;
  IF OLD."validated_at" IS NOT NULL AND (NEW."validated_at" IS DISTINCT FROM OLD."validated_at"
      OR NEW."validated_gate_id" IS DISTINCT FROM OLD."validated_gate_id"
      OR NEW."validated_by_id" IS DISTINCT FROM OLD."validated_by_id") THEN
    RAISE EXCEPTION 'ticket validated_at cannot change once set';
  END IF;

  -- THE TOP RULE, first half: PAID only through a SUCCESS payment. Read FOR
  -- SHARE, so the payment cannot change between this check and the commit.
  IF NEW."payment_status" = 'PAID' AND OLD."payment_status" = 'UNPAID' AND NEW."paid_payment_id" IS NOT NULL THEN
    SELECT "status"::text INTO paying_status FROM "payment" WHERE "id" = NEW."paid_payment_id" FOR SHARE;
    IF paying_status IS DISTINCT FROM 'SUCCESS' THEN
      RAISE EXCEPTION 'ticket PAID refused: payment % is not a SUCCESS payment of this ticket', NEW."paid_payment_id"
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "ticket_guard"
  BEFORE UPDATE ON "ticket"
  FOR EACH ROW EXECUTE FUNCTION "ticket_guard"();


-- The end of a ticket's day: the start of the next day in Africa/Lagos
-- (UTC+1 all year). Needed before the valid_until default below.
CREATE FUNCTION "lagos_day_end"(ts timestamptz) RETURNS timestamptz
LANGUAGE sql STABLE AS $$
  SELECT ((date_trunc('day', ts AT TIME ZONE 'Africa/Lagos') + interval '1 day') AT TIME ZONE 'Africa/Lagos')
$$;


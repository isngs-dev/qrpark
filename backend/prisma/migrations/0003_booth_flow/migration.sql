-- The facts of a payment never change, and SUCCESS and DUPLICATE are final
-- (THE FREEZE: no refunds or reversals in release 1; lifted only by a future
-- migration if Phase 2 adds them). Late answers stay possible: PENDING,
-- FAILED or ABANDONED may still become SUCCESS or DUPLICATE.
CREATE FUNCTION "payment_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."ticket_id" IS DISTINCT FROM OLD."ticket_id" THEN RAISE EXCEPTION 'payment ticket_id cannot change'; END IF;
  IF NEW."amount_kobo" IS DISTINCT FROM OLD."amount_kobo" THEN RAISE EXCEPTION 'payment amount_kobo cannot change'; END IF;
  IF NEW."method" IS DISTINCT FROM OLD."method" THEN RAISE EXCEPTION 'payment method cannot change'; END IF;
  IF NEW."reference" IS DISTINCT FROM OLD."reference" THEN RAISE EXCEPTION 'payment reference cannot change'; END IF;
  IF NEW."idempotency_key" IS DISTINCT FROM OLD."idempotency_key" THEN RAISE EXCEPTION 'payment idempotency_key cannot change'; END IF;
  IF NEW."operator_id" IS DISTINCT FROM OLD."operator_id" THEN RAISE EXCEPTION 'payment operator_id cannot change'; END IF;
  IF NEW."gate_id" IS DISTINCT FROM OLD."gate_id" THEN RAISE EXCEPTION 'payment gate_id cannot change'; END IF;
  IF NEW."device_ref" IS DISTINCT FROM OLD."device_ref" THEN RAISE EXCEPTION 'payment device_ref cannot change'; END IF;
  IF NEW."site_id" IS DISTINCT FROM OLD."site_id" THEN RAISE EXCEPTION 'payment site_id cannot change'; END IF;
  IF OLD."status"::text IN ('SUCCESS', 'DUPLICATE') AND NEW."status" IS DISTINCT FROM OLD."status" THEN
    RAISE EXCEPTION 'payment % is %: its status cannot change', OLD."id", OLD."status";
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "payment_guard"
  BEFORE UPDATE ON "payment"
  FOR EACH ROW EXECUTE FUNCTION "payment_guard"();

